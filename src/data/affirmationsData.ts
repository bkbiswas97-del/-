/**
 * Returns today's affirmation deterministically based on date (day of year)
 */
export function getTodaysAffirmation(): Affirmation {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % AFFIRMATIONS_DATA.length;
  return AFFIRMATIONS_DATA[index];
}
